/** Lower-case, strip accents and punctuation, collapse spaces: "São Paulo" → "sao paulo". */
export function normalizeQuery(s: string): string {
  return s
    .normalize("NFKD")
    .replace(/\p{M}+/gu, "")
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim()
    .replace(/\s+/g, " ");
}
